    @classmethod
    def classify(cls, text: str) -> dict[str, Any] | None:
        if not text or not text.strip():
            return {"intent": "empty"}

        lower_text = "".join(text.lower().split())  # Нормализуем текст (убираем пробелы)

        # === ШАГ 1: ПРОВЕРКА НА ПОДТВЕРЖДЕНИЕ ЗАКАЗА (ПРИОРИТЕТ №1) ===
        # ВАЖНО: Список должен совпадать с тем, что у вас в confirm_order_tool!
        affirmative_keywords = [
            "да",
            "yes",
            "подтверждаю",
            "ок",
            "ага",
            "конечно",
            "хорошо",
            "оформляй",
            "заказывай",
            "готово",
            "lf",
            "yf",  # транслит-да
        ]

        negative_keywords = [
            "нет",
            "no",
            "не надо",
            "отмена",
            "не подтверждаю",
            "стоп",
            "пока",
            "ненадо",
            "yt",
            "ytn",
        ]

        is_affirmative = any(keyword == lower_text for keyword in affirmative_keywords)
        is_negative = any(keyword == lower_text for keyword in negative_keywords)

        # Проверка одиночных букв (д, l, н, y)
        single_char_map = {"д": True, "l": True, "n": False, "y": True}
        if len(lower_text) == 1 and lower_text in single_char_map:
            is_affirmative = single_char_map[lower_text]
            is_negative = not is_affirmative

        # ЕСЛИ ЭТО ПОДТВЕРЖДЕНИЕ — СРАЗУ ПРОПУСКАЕМ ФИЛЬТР
        if is_affirmative or is_negative:
            logger.info(f"Middleware пропустил команду управления заказом: '{text}'")
            return None

        # === ШАГ 2: ОБРАБОТКА SMALL TALK И ОШИБОК (только если это НЕ команда) ===
        for intent, patterns in cls.PATTERNS.items():
            for pattern in patterns:
                if re.search(pattern, text.lower()):
                    response = cls.RESPONSES.get(intent, cls.RESPONSES["unknown"])

                    action = None
                    if intent == "restart_session":
                        action = "reset_graph_state"
                    elif intent == "error_correction":
                        action = "clear_last_entity"
                    elif intent == "lost_context":
                        action = "full_reset"

                    return {
                        "step": "init",
                        "response_message": response,
                        "need_clarification": False,
                        "action": action,
                        "skip_graph": True,
                    }

        return None
